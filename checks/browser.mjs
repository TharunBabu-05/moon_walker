import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
try{
  await page.goto('http://127.0.0.1:8000',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.selene?.snapshot().ready,{},{timeout:60000});
  await page.screenshot({path:'artifacts/01-welcome.png'});
  await page.getByRole('button',{name:'STEP ONTO THE MOON'}).click();
  await page.keyboard.press('Escape');
  await page.screenshot({path:'artifacts/02-first-person.png'});
  await page.keyboard.press('Digit2');
  await page.waitForFunction(()=>window.selene.snapshot().mode==='follow');
  const initial=await page.evaluate(()=>window.selene.snapshot());
  await page.keyboard.down('KeyW');
  await page.waitForFunction(()=>window.selene.snapshot().player.distance>.45,{},{timeout:15000});
  const moving=await page.evaluate(()=>window.selene.snapshot());
  assert.ok(moving.player.speed>.1);
  assert.notDeepEqual(moving.feet.map(f=>f.kneeQuaternion),initial.feet.map(f=>f.kneeQuaternion),'knees articulate while walking');
  await page.screenshot({path:'artifacts/03-walking.png'});
  await page.waitForFunction(()=>window.selene.snapshot().footsteps>=4,{},{timeout:20000});
  await page.keyboard.up('KeyW');
  await page.waitForFunction(()=>window.selene.snapshot().player.speed<.01);
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>{const s=window.selene.snapshot();return !s.player.grounded&&s.player.y-s.ground>.4;},{},{timeout:12000});
  await page.screenshot({path:'artifacts/04-jump.png'});
  await page.waitForFunction(()=>window.selene.snapshot().player.grounded,{},{timeout:15000});
  const beforeOrbit=await page.evaluate(()=>window.selene.snapshot().player);
  await page.keyboard.press('Digit3');
  await page.waitForFunction(()=>window.selene.snapshot().mode==='orbit');
  await page.screenshot({path:'artifacts/05-orbit.png'});
  await page.mouse.move(900,440);await page.mouse.wheel(0,-500);
  await page.waitForFunction(()=>window.selene.snapshot().orbitDistance<4000);
  await page.mouse.wheel(0,2300);
  await page.waitForFunction(()=>window.selene.snapshot().orbitDistance>100000);
  await page.getByRole('button',{name:'Earth + Moon'}).click();
  await page.waitForFunction(()=>window.selene.snapshot().orbitDistance>550000);
  await page.screenshot({path:'artifacts/06-earth-moon.png'});
  assert.equal(await page.locator('#earth-label').isVisible(),true);
  assert.equal(await page.locator('#moon-label').isVisible(),true);
  await page.getByRole('button',{name:'Return to my astronaut'}).click();
  await page.waitForFunction(()=>window.selene.snapshot().mode==='follow');
  const afterOrbit=await page.evaluate(()=>window.selene.snapshot().player);
  assert.ok(Math.hypot(beforeOrbit.x-afterOrbit.x,beforeOrbit.z-afterOrbit.z)<.02,'orbital view retains surface position');
  await page.getByRole('button',{name:'Show controls'}).click();assert.equal(await page.locator('#help').isVisible(),true);await page.getByRole('button',{name:'Close controls'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/07-mobile.png'});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);assert.equal(overflow,false);
  console.log(JSON.stringify({passed:true,footsteps:await page.evaluate(()=>window.selene.snapshot().footsteps),errors},null,2));
  assert.deepEqual(errors,[],'no browser or shader errors');
}finally{await browser.close();}
