import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts',{recursive:true});
const base=process.env.SELENE_BASE_URL||'http://127.0.0.1:8000/';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const errors=[];
const context=await browser.newContext({viewport:{width:1440,height:900},permissions:['clipboard-read','clipboard-write']});
const monitor=page=>{page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error'&&!/favicon/.test(m.text()))errors.push(m.text());});};
async function start(url){
  const page=await context.newPage();monitor(page);await page.goto(url);
  await page.waitForFunction(()=>window.selene?.snapshot().ready,{},{timeout:60000});
  await page.getByRole('button',{name:'STEP ONTO THE MOON'}).click();if(!new URL(url).searchParams.has('room'))await page.keyboard.press('Escape');return page;
}
const snapshot=page=>page.evaluate(()=>window.selene.snapshot());
try{
  const host=await start(base);
  await host.keyboard.press('Digit2');await host.waitForFunction(()=>window.selene.snapshot().mode==='follow');await host.locator('#scene').focus();
  await host.keyboard.press('KeyE');await host.waitForFunction(()=>window.selene.snapshot().riding);
  await host.waitForFunction(()=>window.selene.snapshot().rover.grounded);
  const parked=(await snapshot(host)).rover;
  await host.keyboard.down('KeyW');
  await host.waitForFunction(({x,z})=>{const r=window.selene.snapshot().rover;return Math.hypot(r.x-x,r.z-z)>1.2;},parked,{timeout:20000});
  await host.keyboard.down('KeyA');
  await host.waitForFunction(yaw=>Math.abs(window.selene.snapshot().rover.yaw-yaw)>.08,parked.yaw,{timeout:15000});
  await host.keyboard.up('KeyA');await host.keyboard.up('KeyW');await host.keyboard.down('Space');
  await host.waitForFunction(()=>window.selene.snapshot().rover.speed<.15,{},{timeout:20000});
  await host.keyboard.up('Space');await host.screenshot({path:'artifacts/10-buggy-driving.png'});
  await host.keyboard.press('KeyE');await host.waitForFunction(()=>!window.selene.snapshot().riding);
  const exited=await snapshot(host);assert.ok(Math.hypot(exited.player.x-exited.rover.x,exited.player.z-exited.rover.z)>1.4);
  await host.getByRole('button',{name:'Open multiplayer expedition'}).click();
  await host.getByLabel('YOUR CALLSIGN').fill('Luna');await host.getByRole('button',{name:'Start an expedition'}).click();
  await host.waitForFunction(()=>['connected','error'].includes(window.selene.snapshot().network.phase),{},{timeout:25000});
  let h=await snapshot(host);assert.equal(h.network.phase,'connected',await host.locator('#network-status').innerText());
  const code=h.network.code;assert.match(code,/^[a-f0-9]{8}$/);
  const invite=await host.getByLabel('Expedition invite link').inputValue();assert.equal(new URL(invite).searchParams.get('room'),code);
  await host.screenshot({path:'artifacts/11-expedition-invite.png'});
  const guest=await start(invite);assert.equal(await guest.locator('#crew-dialog').isVisible(),true);
  await guest.getByLabel('YOUR CALLSIGN').fill('Orion');await guest.getByRole('button',{name:'Join crew'}).click();
  await guest.waitForFunction(()=>['connected','error'].includes(window.selene.snapshot().network.phase),{},{timeout:25000});
  assert.equal((await snapshot(guest)).network.phase,'connected',await guest.locator('#network-status').innerText());
  await guest.waitForFunction(()=>window.selene.snapshot().remoteCount===1,{},{timeout:20000});
  await host.waitForFunction(()=>window.selene.snapshot().remoteCount===1,{},{timeout:20000});
  await guest.getByRole('button',{name:'Close expedition'}).click();
  await host.bringToFront();await host.getByRole('button',{name:'Close expedition'}).click();await host.locator('#scene').focus();
  const before=(await snapshot(host)).player.distance;await host.keyboard.down('KeyW');
  await host.waitForFunction(d=>window.selene.snapshot().player.distance>d+.5,before,{timeout:20000});await host.keyboard.up('KeyW');
  await guest.waitForFunction(d=>window.selene.snapshot().network.members.some(m=>m.state?.distance>d+.3),before,{timeout:15000});
  await guest.bringToFront();await guest.keyboard.press('Digit2');await guest.locator('#scene').focus();
  await guest.keyboard.press('KeyE');await guest.waitForFunction(()=>window.selene.snapshot().riding);
  await host.waitForFunction(()=>window.selene.snapshot().network.members.some(m=>m.state?.riding),{},{timeout:15000});
  await guest.screenshot({path:'artifacts/12-multiplayer-surface.png'});
  await guest.getByRole('button',{name:'Open multiplayer expedition'}).click();await guest.getByRole('button',{name:'Leave expedition'}).click();
  await host.waitForFunction(()=>window.selene.snapshot().network.count===1,{},{timeout:15000});
  await host.setViewportSize({width:390,height:844});await host.screenshot({path:'artifacts/13-mobile-expedition.png'});
  assert.equal(await host.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[],'no browser or graphics errors');
  console.log(JSON.stringify({passed:true,buggy:'drive / steer / brake / exit',multiplayer:'two peers connected, movement and vehicle state replicated, guest departure cleaned up',room:code,errors},null,2));
}finally{await browser.close();}
